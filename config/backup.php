<?php

/**
 * Бэкап БД, управляемый администраторами из Telegram (/backup_on, /backup_time ...).
 * Включение, время и статус хранятся в таблице bot_settings, здесь — то, что
 * задаётся на сервере и недоступно из чата (куда слать и чем шифровать).
 */
return [
    // Чат, куда отправляются зашифрованные копии (id пользователя или закрытой группы)
    'chat_id' => env('BACKUP_TELEGRAM_CHAT_ID'),

    // Пароль шифрования копий. Без него копии не отправляются (не шлём данные открытым текстом)
    'passphrase' => env('BACKUP_PASSPHRASE'),

    // Часовой пояс, в котором задаётся и показывается время запуска
    'timezone' => env('BACKUP_TIMEZONE', 'Europe/Minsk'),

    // Сколько дней хранить копии на самом сервере
    'keep_days' => (int)env('BACKUP_KEEP_DAYS', 14),

    // Лимит Telegram для бота — 50 МБ, оставляем запас
    'max_upload_bytes' => 45 * 1024 * 1024,

    'dir' => storage_path('app/backups'),
];
